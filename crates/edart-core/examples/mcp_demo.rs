//! The MCP connector with a pretend iPhone, for trying a client against it
//! without a Mac or a phone:
//!
//! ```sh
//! cargo run -p edart-core --example mcp_demo
//! claude mcp add --transport http edart http://127.0.0.1:7391/mcp
//! ```

use std::sync::Arc;

use edart_core::gesture::{Gesture, Screen};
use edart_core::mcp::http::{url, HttpServer, DEFAULT_PORT, LAST_PORT};
use edart_core::mcp::server::Server;
use edart_core::mcp::{CallLog, ControlLink, Frame, Phone, PhoneStatus};

/// The smallest valid JPEG: one grey pixel.
const PIXEL: &[u8] = &[
    0xff, 0xd8, 0xff, 0xdb, 0x00, 0x43, 0x00, 0x03, 0x02, 0x02, 0x02, 0x02, 0x02, 0x03, 0x02, 0x02,
    0x02, 0x03, 0x03, 0x03, 0x03, 0x04, 0x06, 0x04, 0x04, 0x04, 0x04, 0x04, 0x08, 0x06, 0x06, 0x05,
    0x06, 0x09, 0x08, 0x0a, 0x0a, 0x09, 0x08, 0x09, 0x09, 0x0a, 0x0c, 0x0f, 0x0c, 0x0a, 0x0b, 0x0e,
    0x0b, 0x09, 0x09, 0x0d, 0x11, 0x0d, 0x0e, 0x0f, 0x10, 0x10, 0x11, 0x10, 0x0a, 0x0c, 0x12, 0x13,
    0x12, 0x10, 0x13, 0x0f, 0x10, 0x10, 0x10, 0xff, 0xc9, 0x00, 0x0b, 0x08, 0x00, 0x01, 0x00, 0x01,
    0x01, 0x01, 0x11, 0x00, 0xff, 0xcc, 0x00, 0x06, 0x00, 0x10, 0x10, 0x05, 0xff, 0xda, 0x00, 0x08,
    0x01, 0x01, 0x00, 0x00, 0x3f, 0x00, 0xd2, 0xcf, 0x20, 0xff, 0xd9,
];

struct Pretend;

impl Phone for Pretend {
    fn status(&self) -> PhoneStatus {
        PhoneStatus {
            phone_name: Some("Pretend iPhone".into()),
            control: ControlLink::Usb,
            mirror_available: true,
        }
    }
    fn screenshot(&self) -> Result<Frame, String> {
        Ok(Frame {
            jpeg: PIXEL.to_vec(),
            width: 1,
            height: 1,
        })
    }
    fn perform(&self, gesture: &Gesture, screen: Screen) -> Result<(), String> {
        println!("{gesture:?} on {screen:?}");
        Ok(())
    }
}

fn main() -> std::io::Result<()> {
    let handler = Arc::new(Server::new(Pretend, Arc::new(CallLog::default())));
    let server = HttpServer::start(handler, DEFAULT_PORT..=LAST_PORT)?;
    println!("Listening on {}. Ctrl-C to stop.", url(server.port()));
    loop {
        std::thread::park();
    }
}
